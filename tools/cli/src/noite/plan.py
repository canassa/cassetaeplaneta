"""The unit plan as a committed text file (``db/plan.tsv``).

The DB is local and can be lost; the plan (what the design pass decided) must
not be. It holds, one tab-separated record per line, sorted:

* ``unit``   name, kind, path, notes
* ``fn``     addr, unit, name (name is informational)
* ``status`` addr, status, absorbed_by, notes — hand-set ``dead`` / ``absorbed`` /
  ``replaced`` only (``ported`` / ``in_progress`` come from ``@orig`` tags via
  ``noite check --fix-status``)
* ``dep``    unit, depends_on, note — manual unit deps only (``auto`` ones are
  re-derived by ``noite unit dep infer``)

Fields escape ``\\``, tab and newline. Recovery: ``noite import`` on an empty DB
applies the plan after the Ghidra snapshot; ``noite plan apply`` does it by hand.
Apply only adds and updates (it never clears), so it is safe on a live DB.
"""

from __future__ import annotations

import sqlite3
from dataclasses import dataclass
from pathlib import Path

PLAN_REL = "db/plan.tsv"
HAND_STATUSES = ("dead", "absorbed", "replaced")
_HEADER = (
    "# noite plan: units, function assignments, hand-set statuses, manual unit deps.\n"
    "# Generated by `noite plan export` (automatic on main); apply with `noite plan apply`.\n"
)


class PlanError(RuntimeError):
    pass


def _esc(v: str | None) -> str:
    return (v or "").replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")


def _unesc(v: str) -> str:
    out, i = [], 0
    while i < len(v):
        if v[i] == "\\" and i + 1 < len(v):
            out.append({"t": "\t", "n": "\n"}.get(v[i + 1], v[i + 1]))
            i += 2
        else:
            out.append(v[i])
            i += 1
    return "".join(out)


def _line(*fields: str | None) -> str:
    return "\t".join(_esc(f) for f in fields)


def render(conn: sqlite3.Connection) -> str:
    lines: list[str] = []
    for r in conn.execute("SELECT name, kind, path, notes FROM units ORDER BY name"):
        lines.append(_line("unit", r["name"], r["kind"], r["path"], r["notes"]))
    for r in conn.execute(
        "SELECT addr, unit, name FROM functions WHERE unit IS NOT NULL ORDER BY addr"
    ):
        lines.append(_line("fn", r["addr"], r["unit"], r["name"]))
    marks = ",".join(f"'{s}'" for s in HAND_STATUSES)
    for r in conn.execute(
        "SELECT addr, status, absorbed_by, notes FROM functions "
        f"WHERE status_auto = 0 AND status IN ({marks}) ORDER BY addr"
    ):
        lines.append(_line("status", r["addr"], r["status"], r["absorbed_by"], r["notes"]))
    for r in conn.execute(
        "SELECT unit, depends_on, note FROM unit_deps WHERE source = 'manual' "
        "ORDER BY unit, depends_on"
    ):
        lines.append(_line("dep", r["unit"], r["depends_on"], r["note"]))
    # Stable section order (unit, fn, status, dep), sorted within each.
    return _HEADER + "".join(f"{x}\n" for x in lines)


def write(conn: sqlite3.Connection, path: Path) -> bool:
    """Write the plan; False when the file already holds exactly this."""
    text = render(conn)
    if path.exists() and path.read_text() == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return True


@dataclass
class ApplyResult:
    units: int = 0
    functions: int = 0
    statuses: int = 0
    deps: int = 0
    skipped: int = 0  # records naming a function or unit the DB does not have


def apply(conn: sqlite3.Connection, text: str) -> ApplyResult:
    """Load a plan into the DB (inside the caller's transaction)."""
    res = ApplyResult()
    records: dict[str, list[list[str]]] = {"unit": [], "fn": [], "status": [], "dep": []}
    for n, raw in enumerate(text.splitlines(), 1):
        if not raw or raw.startswith("#"):
            continue
        parts = [_unesc(p) for p in raw.split("\t")]
        if parts[0] not in records:
            raise PlanError(f"plan line {n}: unknown record {parts[0]!r}")
        records[parts[0]].append(parts[1:] + [""] * 4)
    for name, kind, path, notes, *_ in records["unit"]:
        conn.execute(
            "INSERT INTO units (name, path, kind, notes) VALUES (?, ?, ?, ?) "
            "ON CONFLICT (name) DO UPDATE SET kind = excluded.kind, path = excluded.path, "
            "notes = excluded.notes",
            (name, path, kind, notes or None),
        )
        res.units += 1
    funcs = {r[0] for r in conn.execute("SELECT addr FROM functions")}
    for addr, unit, *_ in records["fn"]:
        if addr not in funcs:
            res.skipped += 1
            continue
        conn.execute("UPDATE functions SET unit = ? WHERE addr = ?", (unit, addr))
        res.functions += 1
    for addr, status, by, notes, *_ in records["status"]:
        if addr not in funcs:
            res.skipped += 1
            continue
        conn.execute(
            "UPDATE functions SET status = ?, status_auto = 0, "
            "absorbed_by = COALESCE(?, absorbed_by), notes = COALESCE(?, notes) WHERE addr = ?",
            (status, by or None, notes or None, addr),
        )
        res.statuses += 1
    for unit, on, note, *_ in records["dep"]:
        conn.execute(
            "INSERT INTO unit_deps (unit, depends_on, source, note) VALUES (?, ?, 'manual', ?) "
            "ON CONFLICT (unit, depends_on) DO UPDATE SET source = 'manual', note = excluded.note",
            (unit, on, note or None),
        )
        res.deps += 1
    return res
