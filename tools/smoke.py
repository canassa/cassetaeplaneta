#!/usr/bin/env python3
"""Smoke test: start every INI scene headless and click its objects.

    nix develop -c python3 tools/smoke.py [SCENE...] [--ms N] [--keep DIR] [--one-button]
        [--monkey SEED [--freeze]]
    nix develop -c python3 tools/smoke.py --minigame encaixe|tiro [--monkey SEED] [--ms N]

For each `[section]` with a `Screen=` line, runs
`zig-out/bin/noite --headless --scene NAME` with a generated input script:
for every object line of the section (Local, Animated, Static, Moveable,
Exit, 2Exit, Portable placed there) a right click and a left click at its
centre, a few clicks on the control-panel strip and some mouse moves.
A run fails when noite exits non-zero (panic, unported function, error)
or the allocator reports a leak.
Prints one line per scene and a summary; the failing runs' output is kept
in --keep (default zig-out/smoke/).

`--minigame NAME` runs that ported minigame alone instead (`noite
--minigame NAME`) for 60 s (seeds 1-5, or `--monkey SEED`): ENCAIXE gets
random arrow presses and holds, TIRO random LEFT/RIGHT presses and SPACE
presses at least 110 ms apart (no held SPACE, so BUGS.md T3 cannot make a
run endless: 15 presses end it); a run fails on a non-zero exit, a leak or
no result.
"""

import argparse
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OBJECT_KEYS = ("Local", "Animated", "Static", "Moveable", "Exit", "2Exit")

# Scenes no exit or handler leads to whose data is broken on the disc: the
# original stops with "Erro Fatal" too (backdrop missing / exit to a
# section that does not exist).
EXPECTED_FAIL = {
    "1fchave": "backdrop fase1\\1fcorred\\1fchave.bmp is not on the disc",
    "3fpapmal2": "backdrop fase3\\3fpapclo\\3fpapmal2.bmp is not on the disc",
    "3fpapwin": "its exit leads to [4fsaldan], which does not exist",
}


def sections(ini_text):
    out, cur = {}, None
    for raw in ini_text.splitlines():
        line = raw.strip()
        if line.startswith("[") and line.endswith("]"):
            cur = line[1:-1]
            out[cur] = []
        elif cur is not None and line and not line.startswith(";"):
            out[cur].append(line)
    return out


def fields(line):
    return [f.strip() for f in line.split("=", 1)[1].split(",")]


def num(s):
    try:
        return int(s)
    except ValueError:
        return 0


def targets(lines, portables):
    """Click points (x, y) on the scene's objects."""
    pts = []
    for line in lines:
        key = line.split("=", 1)[0]
        if key not in OBJECT_KEYS:
            continue
        f = fields(line)
        if len(f) < 6:
            continue
        x, y, w, h = num(f[1]), num(f[2]), num(f[4]), num(f[5])
        pts.append((x + max(w, 1) // 2, y + max(h, 1) // 2))
    pts.extend(portables)
    return [(min(max(x, 1), 638), min(max(y, 1), 470)) for x, y in pts]


# Items given in --offers runs: the gift, wallet, bible, wine, shirt,
# present, Oscar and the Martian (every scene's "right item" is one of them).
OFFER_ITEMS = (107, 71, 48, 86, 69, 98, 108, 273)


OFFER_STEP = 8000


def offers_for(pts, ms, one_button=False):
    """Takes the key items, then drags inventory slots onto each target.

    The harness checks each offered item (src/platform/harness.zig,
    `watchOffers`): with B30's fix it must stay where it was released until
    the handler takes it back, and its image must not stay on the screen
    after. In the one-button mode the offers alternate between a left-button
    drag and tap-tap (tap the slot, tap the target)."""
    lines = ["# generated by tools/smoke.py --offers", "300 move 320 240"]
    t = 1000
    # Replies take a few seconds; an offer made while one plays is consumed
    # in its place (BUGS.md B23), which loses the rest of the inventory.
    step = max(OFFER_STEP, (ms - 2000) // max(1, len(pts)))
    for k, (x, y) in enumerate(pts):
        y = min(y, 330)
        sx = 110 + 56 * (k % 8)
        if not one_button:
            lines.append(f"{t} offer {k % 8} {x} {y}")
        elif k % 2 == 0:
            lines += [f"{t} move 320 465", f"{t + 1500} ldown {sx} 430", f"{t + 1600} move {x} 300",
                      f"{t + 1700} move {x} {y}", f"{t + 2000} lup {x} {y}"]
        else:
            lines += [f"{t} move 320 465", f"{t + 1500} click {sx} 430", f"{t + 2000} click {x} {y}"]
        t += step
    return "\n".join(lines) + "\n"


def monkey_for(pts, ms, seed, freeze=False):
    """Random left/right clicks, panel drags and walks, seeded per scene.
    `freeze`: now and then the window loses focus and the game stalls for
    up to 30 s while the clock runs (the web page hidden), then regains it."""
    import random
    rnd = random.Random(seed)
    lines = ["# generated by tools/smoke.py --monkey", "300 move 320 240"]
    t = 600
    while t < ms - 500:
        r = rnd.random()
        if freeze and rnd.random() < 0.08:
            f = rnd.choice((rnd.randrange(100, 2000), rnd.randrange(2000, 30000)))
            lines += [f"{t} focus 0", f"{t} freeze {f}", f"{t + f} focus 1"]
            t += f + rnd.randrange(0, 300)
            continue
        if r < 0.15 and pts:
            x, y = rnd.choice(pts)
            lines.append(f"{t} offer {rnd.randrange(8)} {x} {min(y, 330)}")
            t += 2100
        elif r < 0.25:
            lines.append(f"{t} move {rnd.randrange(640)} {rnd.choice((200, 465))}")
        elif r < 0.35:
            lines.append(f"{t} hold {rnd.choice(('left', 'right', 'up', 'down'))} {rnd.randrange(100, 800)}")
            t += 800
        else:
            x, y = rnd.choice(pts) if pts and r < 0.75 else (rnd.randrange(640), rnd.randrange(480))
            lines.append(f"{t} {rnd.choice(('click', 'rclick', 'rclick'))} {x} {y}")
        t += rnd.randrange(150, 1500)
    return "\n".join(lines) + "\n"


def script_for(pts, ms):
    lines = ["# generated by tools/smoke.py", "500 move 320 240"]
    t = 1000
    step = max(150, (ms - 2000) // max(1, 2 * len(pts) + 6))
    for x, y in pts:
        lines.append(f"{t} rclick {x} {y}")
        t += step
        lines.append(f"{t} click {x} {y}")
        t += step
    for x in (60, 200, 320, 450, 600):  # the control panel strip
        lines.append(f"{t} click {x} 420")
        t += step // 2
    lines.append(f"{t} move 320 100")
    return "\n".join(lines) + "\n"


def arrows_for(ms, seed):
    """Random arrow presses and holds (a minigame alone), seeded."""
    import random
    rnd = random.Random(seed)
    lines = ["# generated by tools/smoke.py --minigame"]
    t = 300
    while t < ms - 500:
        key = rnd.choice(("left", "right", "up", "down", "left", "right"))
        if rnd.random() < 0.2:
            hold = rnd.randrange(60, 900)
            lines.append(f"{t} hold {key} {hold}")
            t += hold
        else:
            lines.append(f"{t} key {key}")
            t += 50
        t += rnd.randrange(20, 700)
    return "\n".join(lines) + "\n"


def tiro_keys_for(ms, seed):
    """TIRO: random aim presses and SPACE presses, 110 ms or more apart."""
    import random
    rnd = random.Random(seed)
    lines = ["# generated by tools/smoke.py --minigame tiro"]
    t = 300
    while t < ms - 500:
        key = rnd.choice(("left", "right", "space", "space", "space"))
        lines.append(f"{t} key {key}")
        t += 110 + rnd.randrange(0, 1500)
    return "\n".join(lines) + "\n"


KEYS_FOR = {"tiro": tiro_keys_for}


def minigame(args):
    keep = pathlib.Path(args.keep)
    keep.mkdir(parents=True, exist_ok=True)
    ms = 60000 if args.ms_default else args.ms
    seeds = [args.monkey] if args.monkey is not None else [1, 2, 3, 4, 5]
    failed = []
    for seed in seeds:
        name = f"{args.minigame}-{seed}"
        sc = keep / f"{name}.input"
        sc.write_text(KEYS_FOR.get(args.minigame, arrows_for)(ms, f"{seed}:{args.minigame}"))
        cmd = [args.exe, "--headless", "--quiet", "--minigame", args.minigame, "--ms", str(ms), "--input", str(sc)]
        if args.fix:
            cmd += ["--fix", args.fix]
        try:
            r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=120, errors="replace")
            code, out = r.returncode, r.stdout + r.stderr
        except subprocess.TimeoutExpired as e:
            code, out = "timeout", (e.stdout or b"").decode(errors="replace") + (e.stderr or b"").decode(errors="replace")
        if code == 0 and "leaked" in out:
            code = "leak"
        res = next((l.strip() for l in out.splitlines() if f"] {args.minigame}: " in l), None)
        if code == 0 and res is None:
            code = "no result"
        log = keep / f"{name}.log"
        if code == 0:
            print(f"ok    {name}: {res}")
            log.unlink(missing_ok=True)
            sc.unlink(missing_ok=True)
        else:
            log.write_text(out)
            first = next((l for l in out.splitlines() if "panic" in l), "")
            print(f"FAIL  {name} ({code}) {first.strip()}")
            failed.append(name)
    print(f"\n{len(seeds) - len(failed)}/{len(seeds)} runs ok")
    if failed:
        print(f"logs in {keep}")
    sys.exit(1 if failed else 0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("scenes", nargs="*")
    ap.add_argument("--ms", type=int, default=None)
    ap.add_argument("--keep", default=str(ROOT / "zig-out" / "smoke"))
    ap.add_argument("--exe", default=str(ROOT / "zig-out" / "bin" / "noite"))
    ap.add_argument("--offers", action="store_true", help="give the key items to every object instead of clicking")
    ap.add_argument("--lose", action="store_true", help="the stub minigames report a loss")
    ap.add_argument("--monkey", type=int, metavar="SEED", help="random clicks, drags and walks (seeded)")
    ap.add_argument("--freeze", action="store_true", help="with --monkey: random time jumps (focus lost, the game stalls)")
    ap.add_argument("--fix", help="BUGS.md fixes to turn on (noite --fix)")
    ap.add_argument("--one-button", action="store_true", help="the one-button control mode (noite --one-button)")
    ap.add_argument("--minigame", metavar="NAME", help="run that ported minigame alone with random keys")
    args = ap.parse_args()
    args.ms_default = args.ms is None
    if args.minigame:
        return minigame(args)
    if args.ms is None:
        args.ms = 6000

    secs = sections((ROOT / "assets" / "CASSETA.INI").read_text(encoding="latin-1"))
    portables = {}
    for line in secs.get("Casseta", []):
        if line.startswith(("Portable=", "ZoomPort=")):
            f = fields(line)
            portables.setdefault(f[1].lower(), []).append((num(f[2]) + 20, num(f[3]) + 20))
    scenes = [s for s, ls in secs.items() if any(l.startswith("Screen=") for l in ls)]
    if args.scenes:
        scenes = [s for s in scenes if s.lower() in {a.lower() for a in args.scenes}]

    keep = pathlib.Path(args.keep)
    keep.mkdir(parents=True, exist_ok=True)
    failed, xfailed, origs = [], [], []
    for name in scenes:
        pts = targets(secs[name], portables.get(name.lower(), []))
        sc = keep / f"{name}.input"
        ms = args.ms
        if args.monkey is not None:
            sc.write_text(monkey_for(pts, ms, f"{args.monkey}:{name}", args.freeze))
        elif args.offers:
            # Every target gets its offer, and the last reply its end.
            if args.ms_default:
                ms = max(ms, OFFER_STEP * len(pts) + 8000)
            sc.write_text(offers_for(pts, ms, args.one_button))
        else:
            sc.write_text(script_for(pts, ms))
        cmd = [args.exe, "--headless", "--quiet", "--scene", name, "--ms", str(ms), "--input", str(sc)]
        if args.offers or args.monkey is not None:
            cmd += ["--take", ",".join(str(i) for i in OFFER_ITEMS)]
        if args.fix:
            cmd += ["--fix", args.fix]
        if args.one_button:
            cmd += ["--one-button"]
        if args.lose:
            cmd += ["--minigame", "lose"]
        try:
            r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=120, errors="replace")
            code, out = r.returncode, r.stdout + r.stderr
        except subprocess.TimeoutExpired as e:
            code, out = "timeout", (e.stdout or b"").decode(errors="replace") + (e.stderr or b"").decode(errors="replace")
        if code == 0 and "leaked" in out:
            code = "leak"
        log = keep / f"{name}.log"
        orig = next((l for l in out.splitlines() if "panic:" in l and "BUGS.md" in l), None)
        if orig is None and "the original exits here" in out:
            box = next((l for l in out.splitlines() if "MessageBox" in l), "")
            orig = "panic: exit(1) after " + box.split("MessageBox", 1)[-1].strip()
        if code != 0 and name in EXPECTED_FAIL:
            print(f"xfail {name}: {EXPECTED_FAIL[name]}")
            xfailed.append(name)
            log.unlink(missing_ok=True)
            sc.unlink(missing_ok=True)
        elif code != 0 and orig is not None:
            # A crash the original has too (the panic names its BUGS.md entry).
            print(f"orig  {name}: {orig.split('panic:', 1)[1].strip()}")
            origs.append(name)
            log.write_text(out)
        elif code != 0 and name in EXPECTED_FAIL:
            print(f"xfail {name}: {EXPECTED_FAIL[name]}")
            xfailed.append(name)
            log.unlink(missing_ok=True)
            sc.unlink(missing_ok=True)
        elif code == 0:
            print(f"ok    {name}")
            log.unlink(missing_ok=True)
            sc.unlink(missing_ok=True)
        else:
            log.write_text(out)
            first = next((l for l in out.splitlines() if "panic" in l and "report" not in l), "")
            print(f"FAIL  {name} ({code}) {first.strip()}")
            failed.append(name)
    print(f"\n{len(scenes) - len(failed) - len(xfailed) - len(origs)}/{len(scenes)} scenes ok, "
          f"{len(xfailed)} expected failures, {len(origs)} original bugs hit")
    if failed:
        print("failed: " + " ".join(failed))
        print(f"logs in {keep}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
