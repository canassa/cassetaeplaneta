//! Build for the native port of NOITE.EXE (docs/DESIGN.md).
const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    // Debug by default, and never LLVM/LLD: the self-hosted backend and
    // linker keep the edit-build loop fast and link SDL3 fine. If a
    // dependency ever forces LLVM, raise it rather than enabling it here.
    const optimize = b.standardOptimizeOption(.{});

    const mod = b.createModule(.{
        .root_source_file = b.path("src/main.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    // SDL3 from the nix dev shell (pkg-config); declared by hand in
    // src/platform/sdl.zig, no translate-c.
    mod.linkSystemLibrary("SDL3", .{});
    // TinySoundFont + TinyMidiLoader (vendor/tinysoundfont, MIT): the MCI
    // `sequencer` replacement, driven from src/platform/midi.zig. Shift
    // sanitizing is off because tsf/tml shift signed values on purpose.
    mod.addCSourceFile(.{
        .file = b.path("vendor/tinysoundfont/tsf_impl.c"),
        .flags = &.{ "-std=c99", "-fno-sanitize=shift" },
    });
    mod.addIncludePath(b.path("vendor/tinysoundfont"));

    const exe = b.addExecutable(.{
        .name = "noite",
        .root_module = mod,
        .use_llvm = false,
        .use_lld = false,
    });
    b.installArtifact(exe);

    const run_step = b.step("run", "Run the game");
    const run_cmd = b.addRunArtifact(exe);
    run_step.dependOn(&run_cmd.step);
    run_cmd.step.dependOn(b.getInstallStep());
    run_cmd.addPassthruArgs();

    // `src/main.zig` references `src/units.zig` (generated by `noite unit
    // sync`), so every port unit's tests run here. Tests run with the repo
    // root as cwd, so they can read `assets/`.
    const exe_tests = b.addTest(.{
        .root_module = mod,
        .use_llvm = false,
        .use_lld = false,
    });
    const run_tests = b.addRunArtifact(exe_tests);
    run_tests.setCwd(b.path("."));
    const test_step = b.step("test", "Run the port's tests");
    test_step.dependOn(&run_tests.step);

    // `noite initdata` generates a program that prints the defaults of the
    // `// @orig g_*` fields and runs it here against the port's module.
    const dump_step = b.step("initdata", "Print the defaults of the @orig g_* fields (noite initdata)");
    if (b.option([]const u8, "initdata-dump", "Generated dump program (noite initdata)")) |path| {
        const dump_mod = b.createModule(.{
            .root_source_file = .{ .cwd_relative = path },
            .target = target,
            .optimize = optimize,
        });
        dump_mod.addImport("noite", mod);
        const dump = b.addExecutable(.{
            .name = "noite-initdata",
            .root_module = dump_mod,
            .use_llvm = false,
            .use_lld = false,
        });
        dump_step.dependOn(&b.addRunArtifact(dump).step);
    }
}
