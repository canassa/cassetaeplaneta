//! Build for the native port of NOITE.EXE (docs/DESIGN.md).
const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    // Debug by default, and never LLVM/LLD: the self-hosted backend and
    // linker keep the edit-build loop fast and link SDL3 fine. If a
    // dependency ever forces LLVM, raise it rather than enabling it here.
    const optimize = b.standardOptimizeOption(.{});

    const mod = b.createModule(.{
        .root_source_file = b.path("src/main.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    // SDL3 from the nix dev shell (pkg-config); declared by hand in
    // src/platform/sdl.zig, no translate-c.
    mod.linkSystemLibrary("SDL3", .{});
    // TinySoundFont + TinyMidiLoader (vendor/tinysoundfont, MIT): the MCI
    // `sequencer` replacement, driven from src/platform/midi.zig. Shift
    // sanitizing is off because tsf/tml shift signed values on purpose.
    mod.addCSourceFile(.{
        .file = b.path("vendor/tinysoundfont/tsf_impl.c"),
        .flags = &.{ "-std=c99", "-fno-sanitize=shift" },
    });
    mod.addIncludePath(b.path("vendor/tinysoundfont"));
    // `-Djardim-probe`: the build `tools/jardim_plan.py` drives (JARDIM's fair enemies' log
    // from the start, no motion frames: they change no state).
    const options = b.addOptions();
    options.addOption(bool, "jardim_probe", b.option(bool, "jardim-probe", "JARDIM planner probe build (tools/jardim_plan.py)") orelse false);
    // `-Djardim-pose=X,Y,ANGLE`: a dev build that starts JARDIM at that pose (units, angle 0..2879;
    // X and Y may have decimals), for the frame dumps of docs/jardim/DESIGN.md "The raycaster".
    options.addOption(?[]const u8, "jardim_pose", b.option([]const u8, "jardim-pose", "JARDIM start pose X,Y,ANGLE (dev builds)"));
    mod.addOptions("build_options", options);

    const exe = b.addExecutable(.{
        .name = "noite",
        .root_module = mod,
        .use_llvm = false,
        .use_lld = false,
    });
    b.installArtifact(exe);

    const run_step = b.step("run", "Run the game");
    const run_cmd = b.addRunArtifact(exe);
    run_step.dependOn(&run_cmd.step);
    run_cmd.step.dependOn(b.getInstallStep());
    run_cmd.addPassthruArgs();

    // `src/main.zig` references `src/units.zig` (generated by `noite unit
    // sync`), so every port unit's tests run here. Tests run with the repo
    // root as cwd, so they can read `assets/`.
    const exe_tests = b.addTest(.{
        .root_module = mod,
        .use_llvm = false,
        .use_lld = false,
    });
    const run_tests = b.addRunArtifact(exe_tests);
    run_tests.setCwd(b.path("."));
    const test_step = b.step("test", "Run the port's tests");
    test_step.dependOn(&run_tests.step);

    // `zig build web`: the browser build in zig-out/web/ (docs/WEB.md) —
    // noite.wasm (wasm32-wasi reactor, self-hosted wasm backend and
    // linker; wasi-libc for TinySoundFont's malloc and math), the page
    // (web/) and manifest.json (tools/web/manifest.py: the disc files the
    // game opens). The disc and the SoundFont are copied next to it by
    // tools/web/build-site.sh, not by this step.
    const web_step = b.step("web", "Build the browser version into zig-out/web");
    const web_mod = b.createModule(.{
        .root_source_file = b.path("src/web_main.zig"),
        .target = b.resolveTargetQuery(.{ .cpu_arch = .wasm32, .os_tag = .wasi }),
        .optimize = optimize,
        .link_libc = true,
    });
    web_mod.addCSourceFile(.{
        .file = b.path("vendor/tinysoundfont/tsf_impl.c"),
        .flags = &.{ "-std=c99", "-fno-sanitize=shift" },
    });
    web_mod.addIncludePath(b.path("vendor/tinysoundfont"));
    web_mod.addOptions("build_options", options);
    const wasm = b.addExecutable(.{
        .name = "noite",
        .root_module = web_mod,
        .use_llvm = false,
        .use_lld = false,
    });
    wasm.entry = .disabled;
    wasm.rdynamic = true;
    wasm.wasi_exec_model = .reactor;
    wasm.stack_size = 8 << 20;
    const web_dir: std.Build.InstallDir = .{ .custom = "web" };
    web_step.dependOn(&b.addInstallArtifact(wasm, .{ .dest_dir = .{ .override = web_dir } }).step);
    web_step.dependOn(&b.addInstallDirectory(.{ .source_dir = b.path("web"), .install_dir = web_dir, .install_subdir = "" }).step);
    const manifest = b.addSystemCommand(&.{ "python3", "tools/web/manifest.py", "--out" });
    manifest.setCwd(b.path("."));
    const manifest_json = manifest.addOutputFileArg("manifest.json");
    manifest.addFileInput(b.path("tools/web/manifest.py"));
    manifest.addFileInput(b.path("tools/web/files.txt"));
    web_step.dependOn(&b.addInstallFileWithDir(manifest_json, web_dir, "manifest.json").step);

    // `zig build sauna-plan -- --start MS`: plans a win of the Corrigida's arcade SAUNA as an input
    // script (src/sauna/plan.zig, driven by `tools/sauna_plan.py --arcade`).
    const plan_step = b.step("sauna-plan", "Plan a SAUNA arcade win (tools/sauna_plan.py --arcade)");
    {
        const plan_mod = b.createModule(.{
            .root_source_file = b.path("src/sauna/plan.zig"),
            .target = target,
            .optimize = .ReleaseFast,
        });
        const plan = b.addExecutable(.{
            .name = "sauna-plan",
            .root_module = plan_mod,
            .use_llvm = false,
            .use_lld = false,
        });
        const run_plan = b.addRunArtifact(plan);
        run_plan.addPassthruArgs();
        plan_step.dependOn(&run_plan.step);
    }

    // `zig build inv-bot -- --games N --reaction MS`: plays the Corrigida's arcade INV as a player with a
    // reaction time (src/inv/arcade/bot.zig, driven by `tools/inv_bot.py`).
    const bot_step = b.step("inv-bot", "A player for the arcade INV (tools/inv_bot.py)");
    {
        const bot_mod = b.createModule(.{
            .root_source_file = b.path("src/inv/arcade/bot.zig"),
            .target = target,
            .optimize = .ReleaseFast,
        });
        const bot = b.addExecutable(.{
            .name = "inv-bot",
            .root_module = bot_mod,
            .use_llvm = false,
            .use_lld = false,
        });
        const run_bot = b.addRunArtifact(bot);
        run_bot.addPassthruArgs();
        bot_step.dependOn(&run_bot.step);
        // Also left in zig-out/bin (`tools/inv_bot.py` runs several at once).
        bot_step.dependOn(&b.addInstallArtifact(bot, .{}).step);
    }

    // `noite initdata` generates a program that prints the defaults of the
    // `// @orig g_*` fields and runs it here against the port's module.
    const dump_step = b.step("initdata", "Print the defaults of the @orig g_* fields (noite initdata)");
    if (b.option([]const u8, "initdata-dump", "Generated dump program (noite initdata)")) |path| {
        const dump_mod = b.createModule(.{
            .root_source_file = .{ .cwd_relative = path },
            .target = target,
            .optimize = optimize,
        });
        dump_mod.addImport("noite", mod);
        const dump = b.addExecutable(.{
            .name = "noite-initdata",
            .root_module = dump_mod,
            .use_llvm = false,
            .use_lld = false,
        });
        dump_step.dependOn(&b.addRunArtifact(dump).step);
    }
}
